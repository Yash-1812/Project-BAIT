def build_textbook_vectorstore(rebuild: bool = False):
    """
    Build FAISS index from the textbook PDF. Returns (store, embedder).
    Will re-create index every run for safety / reproducibility.
    """
    vect_path = os.path.join(VECTORSTORE_DIR, 'textbook.faiss')

    print('Extracting textbook...')
    textbook_text = extract_text_from_pdf(TEXTBOOK_PATH)
    print('Chunking textbook...')
    chunks = chunk_text(textbook_text)
    texts = [c['text'] for c in chunks]
    metas = [c['meta'] for c in chunks]
    ids = [c['id'] for c in chunks]

    print('Embedding chunks (local SentenceTransformer)...')
    embedder = Embedder()
    vectors = embedder.embed_texts(texts)
    dim = vectors[0].shape[0]

    print('Creating FAISS index...')
    store = SimpleFAISSStore(dim=dim, index_path=vect_path)
    store.add(vectors, texts, metas, ids)
    store.save()
    print('Vectorstore created at', vect_path)
    return store, embedder

