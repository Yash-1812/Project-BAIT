import pdfplumber

def extract_text_from_pdf(pdf_path: str) -> str:
    """Extract full text from a PDF file."""
    text_parts = []
    with pdfplumber.open(pdf_path) as pdf:
        for page in pdf.pages:
            text = page.extract_text()
            if text:
                text_parts.append(text)
    return "\n\n".join(text_parts)

def chunk_text(text: str, chunk_size: int = CHUNK_SIZE, overlap: int = CHUNK_OVERLAP) -> List[dict]:
    """Deterministic whitespace tokenizer chunker -> list of {'id','text','meta'}."""
    tokens = text.split()
    chunks = []
    idx = 0
    chunk_id = 0
    while idx < len(tokens):
        chunk_tokens = tokens[idx: idx + chunk_size]
        chunk_text = ' '.join(chunk_tokens)
        chunks.append({
            'id': f'textbook_chunk_{chunk_id}',
            'text': chunk_text,
            'meta': {'source': TEXTBOOK_PATH, 'chunk': chunk_id}
        })
        chunk_id += 1
        idx += chunk_size - overlap
    return chunks

def extract_texts_from_zip(zip_path: str, extract_to: str = '/content/papers_extracted') -> List[Tuple[str, str]]:
    """Unzip and extract plain text from PDFs and .txt inside the zip. Returns list of (filepath, text)."""
    os.makedirs(extract_to, exist_ok=True)
    with zipfile.ZipFile(zip_path, 'r') as z:
        z.extractall(extract_to)

    results = []
    for root, _, files in os.walk(extract_to):
        for fname in files:
            full = os.path.join(root, fname)
            if fname.lower().endswith('.pdf'):
                try:
                    text = extract_text_from_pdf(full)
                    results.append((full, text))
                except Exception as e:
                    print('Failed to read PDF', full, e)
            elif fname.lower().endswith('.txt'):
                try:
                    with open(full, 'r', encoding='utf-8', errors='ignore') as f:
                        results.append((full, f.read()))
                except Exception as e:
                    print('Failed to read txt', full, e)
    return results

