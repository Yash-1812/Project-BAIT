def extract_concepts_from_text(text: str, top_n: int = 3) -> List[str]:
    """Simple noun-chunk or token frequency concept extractor."""
    try:
        import spacy
        nlp = spacy.load('en_core_web_sm')
        doc = nlp(text)
        phrases = [chunk.text.lower() for chunk in doc.noun_chunks]
        if len(phrases) < top_n:
            phrases += [tok.text.lower() for tok in doc if tok.pos_ in ('NOUN', 'PROPN')]
        from collections import Counter
        ctr = Counter(phrases)
        return [p for p, _ in ctr.most_common(top_n)]
    except Exception:
        tokens = [t.strip('.,()').lower() for t in text.split() if len(t) > 3]
        from collections import Counter
        ctr = Counter(tokens)
        return [p for p, _ in ctr.most_common(top_n)]

def extract_questions_from_papers(concepts: List[str], papers_texts: List[Tuple[str, str]], max_questions: int = 10) -> List[dict]:
    """Find question-like sentences in supplied papers that mention any of the concepts."""
    question_sents = []
    for fname, text in papers_texts:
        sents = re.split(r'(?<=[\.!?])\s+', text)
        for s in sents:
            if '?' in s:
                s_low = s.lower()
                for c in concepts:
                    if c.lower() in s_low:
                        question_sents.append({'paper': fname, 'question_sentence': s.strip(), 'concept': c})
                        break
    return question_sents[:max_questions]

