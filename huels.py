def answer_question(question: str, store: SimpleFAISSStore, embedder: Embedder, generator: Generator, top_k: int = TOP_K) -> dict:
    """Embed question, retrieve top-k textbook chunks, and generate an answer using generator."""
    qvec = embedder.embed_texts([question])[0]
    hits = store.search(qvec, k=top_k)
    gen_text = generator.generate_answer(question, hits)
    return {'question': question, 'answer': gen_text, 'context_hits': hits}

