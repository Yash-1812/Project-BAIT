import faiss

class SimpleFAISSStore:
    """Minimal FAISS store mapping vectors -> texts & metadata."""
    def __init__(self, dim: int, index_path: Optional[str] = None):
        self.dim = dim
        self.index = faiss.IndexFlatL2(dim)
        self.ids: List[str] = []
        self.texts: List[str] = []
        self.meta: List[dict] = []
        self.index_path = index_path

    def add(self, vectors: List[np.ndarray], texts: List[str], metas: List[dict], ids: List[str]):
        arr = np.vstack(vectors).astype('float32')
        self.index.add(arr)
        self.ids.extend(ids)
        self.texts.extend(texts)
        self.meta.extend(metas)

    def save(self):
        if self.index_path:
            faiss.write_index(self.index, self.index_path)
            meta_file = self.index_path + '.meta.json'
            with open(meta_file, 'w', encoding='utf-8') as f:
                json.dump({'ids': self.ids, 'texts': self.texts, 'meta': self.meta}, f)

    def search(self, query_vec: np.ndarray, k: int = TOP_K):
        D, I = self.index.search(np.array([query_vec]).astype('float32'), k)
        results = []
        for score, idx in zip(D[0], I[0]):
            if idx < len(self.ids):
                results.append({
                    'id': self.ids[idx],
                    'text': self.texts[idx],
                    'meta': self.meta[idx],
                    'score': float(score)
                })
        return results

