import numpy as np

class Embedder:
    """Local sentence-transformers embedder using all-MiniLM-L6-v2."""
    def __init__(self, model_name: str = "all-MiniLM-L6-v2"):
        from sentence_transformers import SentenceTransformer
        self.model = SentenceTransformer(model_name)

    def embed_texts(self, texts: List[str]) -> List[np.ndarray]:
        """Return list of numpy float32 vectors for given texts."""
        # `encode` supports a list to batch; ensure result is 2D
        embs = self.model.encode(texts, show_progress_bar=False)
        return [np.array(v, dtype=np.float32) for v in embs]

