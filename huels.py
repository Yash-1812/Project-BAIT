class Generator:
    """
    Wrapper around google.generativeai for generation only.
    Expects GEMINI_API_KEY in env or passed before creating this class.
    """
    def __init__(self, api_key: Optional[str] = None, model_name: str = "gemini-2.5-flash"):
        self.api_key = api_key or os.environ.get('GEMINI_API_KEY')
        if not self.api_key:
            raise ValueError("GEMINI_API_KEY not found in environment and not passed to Generator.")
        try:
            import google.generativeai as genai
            genai.configure(api_key=self.api_key)
            self.genai = genai
            # create a model handle
            try:
                self.model = genai.GenerativeModel(model_name)
            except Exception:
                # some versions may not need class instantiation - still store genai for fallback
                self.model = None
        except Exception as e:
            raise RuntimeError("Failed to import/configure google.generativeai: " + str(e))

    def _call_generate(self, prompt: str) -> str:
        """
        Call the Gemini model in a few fallbacks depending on installed genai version.
        """
        # 1) Preferred: GenerativeModel.generate_content(prompt)
        try:
            if self.model is not None and hasattr(self.model, "generate_content"):
                resp = self.model.generate_content(prompt)
                # resp may have .text or .last depending on version
                return getattr(resp, "text", getattr(resp, "last", str(resp)))
        except Exception:
            pass

        # 2) Alternative: GenerativeModel.generate (some SDK variants)
        try:
            if self.model is not None and hasattr(self.model, "generate"):
                resp = self.model.generate(prompt)
                return getattr(resp, "text", getattr(resp, "last", str(resp)))
        except Exception:
            pass

        # 3) Global helper fallback: genai.generate (older/newer variants)
        try:
            resp = self.genai.generate_text(model="gemini-2.5-flash", prompt=prompt)
            # resp structure varies; try known fields:
            if isinstance(resp, dict):
                return resp.get("candidates", [{}])[0].get("content", resp.get("text", str(resp)))
            return str(resp)
        except Exception:
            pass

        # If all fail, raise a helpful error
        raise RuntimeError("Could not call Gemini generate with the installed google.generativeai package. Check package version and API availability.")

    def generate_answer(self, question: str, contexts: List[dict]) -> str:
        """
        Given a user question and retrieved contexts (list of dicts with 'text' and 'meta'),
        produce an answer that must use ONLY these contexts.
        """
        # Build a grounded prompt that forces the model to rely only on contexts
        context_text = "\n\n-----\n\n".join([f"(Chunk {c.get('meta', {}).get('chunk')}):\n{c['text']}" for c in contexts])
        prompt = (
            "You are an assistant that must answer the user's question using ONLY the evidence in the provided contexts below. "
            "Do NOT use outside knowledge or make up facts. If the context does not contain the answer, reply exactly: 'I cannot answer from the textbook.'\n\n"
            f"CONTEXTS:\n{context_text}\n\nQUESTION: {question}\n\n"
            "Answer succinctly and, when using evidence, append the chunk id in square brackets like [chunk_id]."
        )

        resp_text = self._call_generate(prompt)
        # Normalize output type if object-like
        if not isinstance(resp_text, str):
            resp_text = str(resp_text)
        return resp_text

